"""
Pattern generation module for the Caleidoscope project.
"""
from typing import Any
from collections.abc import Callable
from .affinetransformation import Transform2D
from .quadtree import QuadTree, Boundary
from .renderers import Renderer
from .constructed_pattern import ConstructedPattern, Tile


# ============================================================================
# Pattern Class
# ============================================================================


class Pattern:
    """
    A class representing a geometric pattern based on a fundamental tile.

    The pattern is generated by applying a set of transformations (generators)
    derived from edge identifications of a fundamental tile. The class uses
    a queue-based breadth-first approach with QuadTree-based duplicate detection
    to efficiently repeat patterns within a specified region.

    Note that we speak here of "pattern" rather than "tiling" because we do not
    concern ourselves with vertices, edges, and faces of the resulting arrangement
    of tiles. Instead, we focus on the visual pattern created by the repeated
    application of the transformations on a set of lines.
    """

    def __init__(self,
                 vertices: list[tuple[float, float]],
                 edges: list[tuple[int, int, str]],
                 polygons: list[tuple[list[int], str]],
                 center: tuple[float, float],
                 tolerance: float,
                 identifications: list[tuple[tuple[int, int], tuple[int, int], bool]],
                 *,
                 include_inverses: bool = True
                ):
        """
        Initialize a Pattern.

        Args:
            vertices: List of vertex coordinates as tuples (x, y) defining the fundamental tile.
            edges: List of edge tuples (v1_index, v2_index, annotation) connecting vertices.
                   The third element is a string annotation for the edge.
            polygons: List of polygon tuples (vertex_indices, annotation) defining the polygons of the tile.
                      The first element is a list of vertex indices, and the second element is a string annotation.
            center: Tuple (x, y) representing the center point of the fundamental tile.
            tolerance: Maximum distance for considering tile centers as duplicates.
            identifications: List of tuples ((from_v1, from_v2), (to_v1, to_v2), keep_orientation)
                           defining edge identifications for generating transformations.
            include_inverses: If True (the default), the inverse of every generator
                           is also used as a generator (appended after the original
                           ones, skipping inverses that equal an existing generator),
                           so e.g. a translation tiles in both directions. If False,
                           only the generators derived from the identifications are
                           used, which reproduces the construction order of earlier
                           versions.
        """
        self.vertices = vertices
        self.edges = edges
        self.polygons = polygons
        self.center = center
        self.tolerance = tolerance
        self.identifications = identifications
        self.include_inverses = include_inverses
        self._generators = None

    @property
    def generators(self):
        """
        Get the transformation generators (lazy evaluation).

        Generators are computed from the identifications on first access and
        cached for subsequent calls. With `include_inverses`, their inverses
        follow them in the same order, skipping any inverse that equals an
        earlier generator.

        Returns:
            List of Transform2D objects representing the generators.
        """
        if self._generators is None:
            generators = [
                Transform2D.from_two_segments(
                    self.vertices[f[0]],
                    self.vertices[f[1]],
                    self.vertices[t[0]],
                    self.vertices[t[1]],
                    keep_orientation=o,
                )
                for f, t, o in self.identifications
            ]
            if self.include_inverses:
                for generator in list(generators):
                    inverse = generator.inverse()
                    if not any(inverse.is_close(other) for other in generators):
                        generators.append(inverse)
            self._generators = generators
        return self._generators

    def construct(
        self,
        center_x: float = 0,
        center_y: float = 0,
        width: float = 10,
        height: float = 10
    ) -> ConstructedPattern:
        """
        Construct the pattern within a specified boundary.

        Uses a queue-based algorithm with QuadTree duplicate detection to
        generate tiles by composing transformations. The algorithm starts
        with the fundamental tile and iteratively applies generators to
        create new tiles until the boundary is filled.

        The tiles are stored in a ConstructedPattern object that can be
        rendered multiple times with different renderers or filters.

        Args:
            center_x: X-coordinate of the center of the rendering region.
            center_y: Y-coordinate of the center of the rendering region.
            width: Width of the rendering region.
            height: Height of the rendering region.

        Returns:
            A ConstructedPattern object containing all tiles within the boundary.
        """
        boundary = Boundary(center_x, center_y, width / 2, height / 2)

        # Create QuadTree for duplicate detection
        quadtree = QuadTree(boundary)

        # List to store all tiles
        tiles: list[Tile] = []

        # Add fundamental tile with identity transformation and empty generator sequence
        identity = Transform2D()  # Identity transformation
        tiles.append(Tile(self.vertices, self.edges, self.polygons, identity, ()))
        quadtree.insert(self.center, tolerance=self.tolerance)

        # Initialize queue with generators and their indices
        # Each queue item is (transformation, generator_sequence)
        queue: list[tuple[Transform2D, tuple[int, ...]]] = [
            (g, (i,)) for i, g in enumerate(self.generators)
        ]

        # Process queue: apply transforms and add tiles
        while queue:
            transform, gen_sequence = queue.pop(0)
            transformed_center = transform.apply(self.center)

            # Check if this tile position is new (within tolerance)
            if quadtree.insert(transformed_center, tolerance=self.tolerance):
                # Transform vertices and create tile
                transformed_vertices = [transform.apply(v) for v in self.vertices]
                tiles.append(Tile(transformed_vertices, self.edges, self.polygons, transform, gen_sequence))

                # Compose with generators and add to queue
                for i, g in enumerate(self.generators):
                    queue.append((transform.compose(g), gen_sequence + (i,)))

        return ConstructedPattern(tiles, center_x, center_y, width, height)

    def render(
        self,
        renderer: Renderer,
        center_x: float = 0,
        center_y: float = 0,
        width: float = 10,
        height: float = 10,
        edge_filter: Callable[[tuple[int, int, str], Tile], bool] | None = None,
        polygon_filter: Callable[[tuple[tuple[int, ...], str], Tile], bool] | None = None,
        margin: float = 1
    ) -> Any:
        """
        Render the pattern within a specified boundary using the given renderer.

        This is a convenience method that constructs the pattern and immediately
        renders it. For more control (e.g., rendering the same pattern multiple
        times with different filters), use construct() to get a ConstructedPattern
        object and call its render() method.

        Args:
            renderer: A renderer object implementing the Renderer protocol.
                     The renderer handles format-specific rendering logic.
            center_x: X-coordinate of the center of the rendering region.
            center_y: Y-coordinate of the center of the rendering region.
            width: Width of the rendering region.
            height: Height of the rendering region.
            edge_filter: Optional predicate function to filter edges.
                        If provided, only edges for which edge_filter(edge, tile) returns True
                        will be rendered. If None, all edges are rendered.
            polygon_filter: Optional predicate function to filter polygons.
                        If provided, only polygons for which polygon_filter(polygon, tile) returns True
                        will be rendered. If None, all polygons are rendered.
            margin: The distance by which the visible/cropped area is inset
                    from the edges of the rendering region on each side.
                    Passed through to renderer.initialize().

        Returns:
            The rendered output, as determined by renderer.finalize().
            Typically a string for text formats (TikZ, SVG) or an image
            object for raster formats (PNG).
        """
        # Construct the pattern
        constructed = self.construct(center_x, center_y, width, height)

        # Render it
        return constructed.render(
            renderer, edge_filter=edge_filter, polygon_filter=polygon_filter, margin=margin
        )

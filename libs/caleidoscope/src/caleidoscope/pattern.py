"""
Pattern generation module for the Caleidoscope project.
"""
from typing import Any
from .affinetransformation import Transform2D
from .quadtree import QuadTree, Boundary
from .renderers import Renderer


# ============================================================================
# Pattern Class
# ============================================================================


class Pattern:
    """
    A class representing a geometric pattern based on a fundamental tile.

    The pattern is generated by applying a set of transformations (generators)
    derived from edge identifications of a fundamental tile. The class uses
    a queue-based breadth-first approach with QuadTree-based duplicate detection
    to efficiently repeat patterns within a specified region.

    Note that we speak here of "pattern" rather than "tiling" because we do not
    concern ourselves with vertices, edges, and faces of the resulting arrangement
    of tiles. Instead, we focus on the visual pattern created by the repeated
    application of the transformations on a set of lines.
    """

    def __init__(self,
                 vertices: list[tuple[float, float]],
                 edges: list[tuple[int, int] | tuple[int, int, str]],
                 center: tuple[float, float],
                 tolerance: float,
                 identifications: list[tuple[tuple[int, int], tuple[int, int], bool]]
                ):
        """
        Initialize a Pattern.

        Args:
            vertices: List of vertex coordinates as tuples (x, y) defining the fundamental tile.
            edges: List of edge tuples (v1_index, v2_index) or (v1_index, v2_index, annotation)
                  connecting vertices. The optional third element is a string annotation for the edge.
            center: Tuple (x, y) representing the center point of the fundamental tile.
            tolerance: Maximum distance for considering tile centers as duplicates.
            identifications: List of tuples ((from_v1, from_v2), (to_v1, to_v2), keep_orientation)
                           defining edge identifications for generating transformations.
        """
        self.vertices = vertices
        self.edges = edges
        self.center = center
        self.tolerance = tolerance
        self.identifications = identifications
        self._generators = None

    @property
    def generators(self):
        """
        Get the transformation generators (lazy evaluation).

        Generators are computed from the identifications on first access
        and cached for subsequent calls.

        Returns:
            List of Transform2D objects representing the generators.
        """
        if self._generators is None:
            self._generators = [
                Transform2D.from_two_segments(
                    self.vertices[f[0]],
                    self.vertices[f[1]],
                    self.vertices[t[0]],
                    self.vertices[t[1]],
                    keep_orientation=o,
                )
                for f, t, o in self.identifications
            ]
        return self._generators

    def render(
        self,
        renderer: Renderer,
        center_x: float = 0,
        center_y: float = 0,
        width: float = 10,
        height: float = 10
    ) -> Any:
        """
        Render the pattern within a specified boundary using the given renderer.

        Uses a queue-based algorithm with QuadTree duplicate detection to
        generate tiles by composing transformations. The algorithm starts
        with the fundamental tile and iteratively applies generators to
        create new tiles until the boundary is filled.

        Args:
            renderer: A renderer object implementing the Renderer protocol.
                     The renderer handles format-specific rendering logic.
            center_x: X-coordinate of the center of the rendering region.
            center_y: Y-coordinate of the center of the rendering region.
            width: Width of the rendering region.
            height: Height of the rendering region.

        Returns:
            The rendered output, as determined by renderer.finalize().
            Typically a string for text formats (TikZ, SVG) or an image
            object for raster formats (PNG).
        """
        boundary = Boundary(center_x, center_y, width / 2, height / 2)

        # Initialize renderer
        renderer.initialize(center_x=center_x, center_y=center_y, width=width, height=height)

        # Create QuadTree for duplicate detection
        quadtree = QuadTree(boundary)

        # Add fundamental tile
        renderer.render_tile(self.vertices, self.edges)

        # Initialize queue with generators
        queue = [g for g in self.generators]

        # Process queue: apply transforms and add tiles
        while queue:
            transform = queue.pop(0)
            transformed_center = transform.apply(self.center)

            # Check if this tile position is new (within tolerance)
            if quadtree.insert(transformed_center, tolerance=self.tolerance):
                # Transform vertices and render tile
                transformed_vertices = [transform.apply(v) for v in self.vertices]
                renderer.render_tile(transformed_vertices, self.edges)

                # Compose with generators and add to queue
                queue += [transform.compose(g) for g in self.generators]

        return renderer.finalize()
